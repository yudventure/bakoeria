/** Tanggal panjang sesuai bahasa, tanpa lewat zona waktu. */
export function tglBahasa(s: string, b: Bahasa) {
  return new Date(s + "T00:00:00Z").toLocaleDateString(b === "en" ? "en-GB" : "id-ID", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });
}
